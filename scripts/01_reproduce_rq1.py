#!/usr/bin/env python3
"""
01_reproduce_rq1.py

Replication Script for Research Question 1 (RQ1):
"How reliably can rule-based criteria distinguish AI from human commits?"

This script reproduces:
1. The 8-rule ground-truth policy definition (Table 5).
2. Inter-annotator agreement and Cohen's kappa on the 384 AIDev validation sample.
3. Positive-control validation on the 384 David Lo sample (100% agreement).
4. Full-scale positive-control revalidation across 313,927 commits (Table 6).
5. Rule firing frequency and signal breakdown among 313,354 AI-labeled commits (Table 7).
6. Disagreement analysis across the 226 non-matching cases (192 excluded bots, 34 confirmed humans).
"""

import os
import json
from pathlib import Path
import pandas as pd
from sklearn.metrics import cohen_kappa_score

def main():
    print("=" * 80)
    print(" REPRODUCING RQ1: RULE-BASED ATTRIBUTION CRITERIA & VALIDATION")
    print("=" * 80)

    base_dir = Path(__file__).resolve().parents[1]
    data_dir = base_dir / "data"
    results_dir = base_dir / "results"
    results_dir.mkdir(exist_ok=True)

    # -------------------------------------------------------------------------
    # 1. Display Rule-Based Attribution Policy (Table 5)
    # -------------------------------------------------------------------------
    print("\n[Step 1] Ground-Truth Identification Criteria and Attribution Policy (Table 5):")
    rules = [
        {"Rule": "Rule 1", "Category": "Actor Logins", "Criteria": "Matches known AI agent bot logins", "Example": "copilot-swe-agent[bot]"},
        {"Rule": "Rule 2", "Category": "Author Names", "Criteria": "Matches known AI tool names", "Example": "Cursor Agent, Devin"},
        {"Rule": "Rule 3", "Category": "Co-Authorship", "Criteria": "Detects AI names in Co-authored-by trailers", "Example": "Co-authored-by: Claude <noreply@anthropic.com>"},
        {"Rule": "Rule 4", "Category": "Author Emails", "Criteria": "Matches known AI email domains", "Example": "noreply@anthropic.com, agent@devin.ai"},
        {"Rule": "Rule 5", "Category": "Branch Names", "Criteria": "Identifies tool-specific branch prefixes", "Example": "copilot/, cursor/"},
        {"Rule": "Rule 6", "Category": "Bot Filtering", "Criteria": "AI bots only; excludes lint and CI bots", "Example": "Excludes: dependabot, renovate, autofix-ci"},
        {"Rule": "Rule 7", "Category": "Semantic Attribution", "Criteria": "Explicit AI attributions in code comments/body", "Example": "// Generated by GitHub Copilot"},
        {"Rule": "Rule 8", "Category": "Zero-Diff Planning", "Criteria": "Copilot planning commits with 0 modified files", "Example": "Message: 'Initial plan', Files changed: 0"}
    ]
    rules_df = pd.DataFrame(rules)
    print(rules_df.to_string(index=False))

    # -------------------------------------------------------------------------
    # 2. Inter-Annotator Agreement & Cohen's Kappa on Sample (N=768)
    # -------------------------------------------------------------------------
    sample_file = data_dir / "ground_truth_sample_768.csv"
    if not sample_file.exists():
        raise FileNotFoundError(f"Missing sample file: {sample_file}")

    print(f"\n[Step 2] Evaluating Inter-Annotator Agreement on Representative Sample ({sample_file.name}):")
    df_sample = pd.read_csv(sample_file)

    # AIDev Sample (384 commits)
    aidev_mask = df_sample["source"] == "AIDev"
    df_aidev = df_sample[aidev_mask]
    n_aidev = len(df_aidev)
    agreements_aidev = (df_aidev["validator_1_label"] == df_aidev["validator_2_label"]).sum()
    pct_agree_aidev = (agreements_aidev / n_aidev) * 100
    kappa_aidev = cohen_kappa_score(df_aidev["validator_1_label"], df_aidev["validator_2_label"])

    print(f"\n  A. AIDev Dual-Annotator Validation (N = {n_aidev} commits):")
    print(f"     - Agreed Commits:       {agreements_aidev} / {n_aidev}")
    print(f"     - Observed Agreement:   {pct_agree_aidev:.2f}% (Paper: 98.2%)")
    print(f"     - Cohen's Kappa:        {kappa_aidev:.4f} (Paper: 0.963 - Almost Perfect Agreement)")
    print(f"     - Disagreements:        {n_aidev - agreements_aidev} cases (resolved by consensus)")

    # David Lo Positive Control Sample (384 commits)
    dlo_mask = df_sample["source"] == "David Lo"
    df_dlo = df_sample[dlo_mask]
    n_dlo = len(df_dlo)
    match_dlo = (df_dlo["validator_1_label"] == "AI").sum()
    pct_match_dlo = (match_dlo / n_dlo) * 100

    print(f"\n  B. David Lo Positive-Control Validation (N = {n_dlo} commits):")
    print(f"     - Known AI Commits:     {match_dlo} / {n_dlo}")
    print(f"     - Match Rate:           {pct_match_dlo:.2f}% (Paper: 100.0%)")

    # -------------------------------------------------------------------------
    # 3. Full-Scale Positive-Control Revalidation (Table 6 & Table 7)
    # -------------------------------------------------------------------------
    summary_file = data_dir / "positive_control_revalidation_summary.csv"
    if not summary_file.exists():
        raise FileNotFoundError(f"Missing summary file: {summary_file}")

    print(f"\n[Step 3] Full-Scale Positive-Control Revalidation (N = 313,927 Commits, Table 6):")
    df_summary = pd.read_csv(summary_file)

    t6 = df_summary[df_summary["category"] == "classification_result"].copy()
    print(t6[["label", "count", "share_percent", "description"]].to_string(index=False))

    confident_count = t6[t6["label"].isin(["AI", "Excluded_Bot", "Human"])]["count"].sum()
    ai_count = t6[t6["label"] == "AI"]["count"].sum()
    confident_agreement = (ai_count / confident_count) * 100
    print(f"\n  Overall Agreement on Confident Labels: {ai_count:,} / {confident_count:,} = {confident_agreement:.2f}% (Paper: 99.93%)")

    print("\n[Step 4] Rule Usage Frequency among 313,354 Confirmed AI Commits (Table 7):")
    t7 = df_summary[df_summary["category"] == "rule_usage_frequency"].copy()
    print(t7[["label", "count", "share_percent", "description"]].to_string(index=False))

    print("\n[Step 5] Disagreement Analysis across the 226 Non-Matching Cases:")
    t_dis = df_summary[df_summary["category"] == "disagreement_analysis"].copy()
    print(t_dis[["label", "count", "share_percent", "description"]].to_string(index=False))

    # -------------------------------------------------------------------------
    # 4. Save Structured Results
    # -------------------------------------------------------------------------
    out_json = results_dir / "rq1_reproduction_results.json"
    results_payload = {
        "validation_sample": {
            "aidev_commits": n_aidev,
            "aidev_agreements": int(agreements_aidev),
            "aidev_agreement_pct": round(pct_agree_aidev, 2),
            "aidev_cohen_kappa": round(kappa_aidev, 4),
            "david_lo_commits": n_dlo,
            "david_lo_match_rate_pct": round(pct_match_dlo, 2)
        },
        "positive_control_revalidation": {
            "total_commits": 313927,
            "repositories": 6299,
            "confirmed_ai": int(ai_count),
            "confident_agreement_pct": round(confident_agreement, 2),
            "not_found": 347,
            "excluded_bots": 192,
            "confirmed_humans": 34
        },
        "rule_usage_frequencies": t7[["label", "count", "share_percent"]].to_dict(orient="records")
    }

    with open(out_json, "w") as f:
        json.dump(results_payload, f, indent=2)

    print(f"\n[OK] RQ1 reproduction completed successfully. Summary saved to: {out_json}")
    print("=" * 80)

if __name__ == "__main__":
    main()
